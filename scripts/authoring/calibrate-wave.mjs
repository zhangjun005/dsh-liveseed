// Offline, character-specific keyframe authoring. Reads local bone landmarks;
// exports rotations only, never geometry, textures, bone positions or screenshots.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { Bone, Skeleton, SkinnedMesh, BufferGeometry, MeshBasicMaterial } from 'three';
import { NativePose } from '../../dist/client/character/pose.js';

const [modelPath, output = 'src/client/character/clips.generated.ts'] = process.argv.slice(2);
if (!modelPath) throw new Error('Usage: node scripts/authoring/calibrate-wave.mjs <local.pmx> [output.ts]; run pnpm build first');
const { Parser } = createRequire(import.meta.url)('mmd-parser');
const bytes = readFileSync(modelPath);
const model = new Parser().parsePmx(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength), true);
const bones = model.bones.map(entry => { const bone = new Bone(); bone.name = entry.name; bone.position.fromArray(entry.position); return bone; });
const mesh = new SkinnedMesh(new BufferGeometry(), new MeshBasicMaterial());
// Compute local positions from immutable landmarks (parents may precede children).
model.bones.forEach((entry, i) => {
  bones[i].position.fromArray(entry.position);
  if (entry.parentIndex >= 0) bones[i].position.sub({ x: model.bones[entry.parentIndex].position[0], y: model.bones[entry.parentIndex].position[1], z: model.bones[entry.parentIndex].position[2] });
  (entry.parentIndex >= 0 ? bones[entry.parentIndex] : mesh).add(bones[i]);
});
mesh.bind(new Skeleton(bones));
const pose = new NativePose(mesh, 1);
const mask = ['右肩', '右腕', '右ひじ', '右手首'];
const duration = 2.2, fps = 30, count = Math.round(duration * fps);
const frames = [];
pose.apply(0); mesh.updateMatrixWorld(true);
const capture = t => ({ t, rotations: Object.fromEntries(mask.map(name => [name, bones.find(b => b.name === name).quaternion.toArray().map(v => +v.toFixed(7))])) });
frames.push(capture(0));
pose.gesture('wave');
for (let i = 1; i <= count; i++) {
  pose.apply(3 / count); mesh.updateMatrixWorld(true);
  if (i === count) { pose.gesture('reset'); pose.apply(0); }
  frames.push(capture(i / fps));
}
const clip = { name: 'wave-small', fps, duration, mask, reference: 'clip-first-frame', interpolation: 'calibrated-limb-directions@30fps', frames,
  source: { tool: 'LiveSeed offline calibrated wave v1', author: 'AI-authored limb direction curves, pending user visual approval', poseSourceSha256: createHash('sha256').update(readFileSync('src/client/character/pose.ts')).digest('hex') } };
writeFileSync(output, '// Generated by scripts/authoring/calibrate-wave.mjs; rotations only.\nexport const bakedClips = ' + JSON.stringify({ 'wave-small': clip }, null, 2) + ' as const;\n');
console.log(`Authored ${frames.length} frames on ${mask.length} control bones.`);
