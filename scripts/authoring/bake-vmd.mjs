// Authoring tool: bake a VMD motion into the character runtime's clip format.
//
// Why bake instead of playing VMD at runtime: the character runtime must write an authored pose
// every frame before MMD resolves grants / IK / physics, so it must not hand playback to an
// AnimationMixer it does not own. Baking keeps the runtime a pure sampler.
//
// The MMD bezier interpolation table is honoured while sampling (MPL writes ease-in-out curves),
// so the baked 30 fps frames are not a linear approximation of the authored timing.
//
// The MPL compiler is GPL-3.0 and is only run offline; this script consumes its VMD output.
// three-mmd / mmd-parser are MIT.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { basename, resolve } from 'node:path';
import { createRequire } from 'node:module';
import { Quaternion, Vector3 } from 'three';

const require = createRequire(import.meta.url);
const { Parser } = require('mmd-parser');

const [vmdPath, clipName, outPath, mplPath] = process.argv.slice(2);
if (!vmdPath || !clipName || !outPath) {
  throw new Error('usage: node scripts/authoring/bake-vmd.mjs <motion.vmd> <clip-name> <out.ts> [source.mpl]');
}

const buffer = readFileSync(resolve(vmdPath));
const arrayBuffer = buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength);
const vmd = new Parser().parseVmd(arrayBuffer, true);
const vmdSha256 = createHash('sha256').update(buffer).digest('hex');
const mplSha256 = mplPath ? createHash('sha256').update(readFileSync(resolve(mplPath))).digest('hex') : null;

/** MMD stores 4 channels of cubic-bezier control points: X, Y, Z, rotation. */
const channelPoints = (interpolation, channel) => [
  interpolation[channel] / 127,
  interpolation[4 + channel] / 127,
  interpolation[8 + channel] / 127,
  interpolation[12 + channel] / 127,
];
const bezier = (u, a, b) => 3 * (1 - u) ** 2 * u * a + 3 * (1 - u) * u * u * b + u ** 3;
function eased(ratio, [x1, y1, x2, y2]) {
  if (!(x1 > 0 || y1 > 0 || x2 < 1 || y2 < 1)) return ratio;
  let low = 0, high = 1;
  for (let i = 0; i < 24; i++) {
    const mid = (low + high) / 2;
    if (bezier(mid, x1, x2) < ratio) low = mid; else high = mid;
  }
  return bezier((low + high) / 2, y1, y2);
}

const byBone = new Map();
for (const motion of vmd.motions) {
  const list = byBone.get(motion.boneName) ?? [];
  list.push(motion);
  byBone.set(motion.boneName, list);
}
for (const list of byBone.values()) list.sort((a, b) => a.frameNum - b.frameNum);

const fps = 30;
const maxFrame = Math.max(...vmd.motions.map(m => m.frameNum));
const duration = maxFrame / fps;
const mask = [...byBone.keys()].sort();

const frames = [];
for (let frame = 0; frame <= maxFrame; frame++) {
  const rotations = {};
  const positions = {};
  for (const [bone, list] of byBone) {
    let index = 0;
    while (index + 1 < list.length && list[index + 1].frameNum <= frame) index++;
    const a = list[index];
    const b = list[Math.min(index + 1, list.length - 1)];
    const span = b.frameNum - a.frameNum;
    const ratio = span > 0 ? (frame - a.frameNum) / span : 0;
    const qa = new Quaternion(...a.rotation).normalize();
    const qb = new Quaternion(...b.rotation).normalize();
    const q = qa.clone().slerp(qb, eased(ratio, channelPoints(a.interpolation, 3)));
    rotations[bone] = q.toArray().map(value => +value.toFixed(6));
    const pa = new Vector3(...a.position), pb = new Vector3(...b.position);
    if (pa.lengthSq() > 0 || pb.lengthSq() > 0) {
      const position = new Vector3();
      for (let axis = 0; axis < 3; axis++) {
        const easedRatio = eased(ratio, channelPoints(a.interpolation, axis));
        position.setComponent(axis, pa.getComponent(axis) + (pb.getComponent(axis) - pa.getComponent(axis)) * easedRatio);
      }
      if (position.lengthSq() > 0) positions[bone] = position.toArray().map(value => +value.toFixed(6));
    }
  }
  frames.push(Object.keys(positions).length ? { t: +(frame / fps).toFixed(4), rotations, positions } : { t: +(frame / fps).toFixed(4), rotations });
}

const generated = {
  name: clipName,
  fps,
  duration: +duration.toFixed(4),
  mask,
  // Frame 0 of an MPL script is its own rest pose, not this model's calibrated idle stance.
  reference: 'clip-first-frame',
  interpolation: 'mmd-bezier-sampled@30fps',
  frames,
  source: {
    tool: 'MMD-MPL 0.3.6 (GPL-3.0, offline authoring only)',
    vmd: basename(vmdPath),
    vmdSha256,
    ...(mplPath ? { mpl: basename(mplPath), mplSha256 } : {}),
  },
};

const header = `// Generated by scripts/authoring/bake-vmd.mjs. Do not edit by hand.\n// Regenerate from the VMD listed in source.vmdSha256. MMD interpolation was sampled at 30 fps.\n`;
writeFileSync(resolve(outPath), header + `export const bakedClips = ${JSON.stringify({ [clipName]: generated }, null, 2)} as const;\n`);
process.stdout.write(`baked '${clipName}': ${frames.length} frames, ${mask.length} bones (${mask.join(', ')}), ${duration}s -> ${outPath}\n`);
