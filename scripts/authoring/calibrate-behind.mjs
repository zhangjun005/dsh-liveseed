// Offline authored keyframes; local PMX landmarks never enter the output.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { Bone, Skeleton, SkinnedMesh, BufferGeometry, MeshBasicMaterial, Vector3, Quaternion } from 'three';
import { NativePose } from '../../dist/client/character/pose.js';
const [path] = process.argv.slice(2);
if (!path) throw new Error('Pass a local PMX path after pnpm build.');
const {Parser} = createRequire(import.meta.url)('mmd-parser');
const bytes = readFileSync(path);
const model = new Parser().parsePmx(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset+bytes.byteLength),true);
const bones = model.bones.map(b => {const node=new Bone();node.name=b.name;return node;});
const mesh = new SkinnedMesh(new BufferGeometry(),new MeshBasicMaterial());
model.bones.forEach((b,i)=>{
  bones[i].position.fromArray(b.position);
  if(b.parentIndex>=0) bones[i].position.sub(new Vector3(...model.bones[b.parentIndex].position));
  (b.parentIndex>=0?bones[b.parentIndex]:mesh).add(bones[i]);
});
mesh.bind(new Skeleton(bones));
const byName=new Map(bones.map(b=>[b.name,b]));
const get=name=>{const b=byName.get(name);if(!b)throw new Error('Missing control '+name);return b;};
const pose=new NativePose(mesh,1);
const mask=['上半身','上半身1','上半身2','首','頭',...['右','左'].flatMap(s=>[s+'腕',s+'ひじ',s+'手首'])];
const ease=t=>{t=Math.max(0,Math.min(1,t));return t*t*t*(t*(t*6-15)+10);};
function aim(bone,end,direction){
  mesh.updateMatrixWorld(true);
  const from=end.getWorldPosition(new Vector3()).sub(bone.getWorldPosition(new Vector3())).normalize();
  const q=new Quaternion().setFromUnitVectors(from,direction.clone().normalize()).multiply(bone.getWorldQuaternion(new Quaternion()));
  bone.quaternion.copy(bone.parent.getWorldQuaternion(new Quaternion()).invert().multiply(q));
}
const fps=30,duration=4.5,frames=[];
for(let i=0;i<=duration*fps;i++){
  const t=i/fps;
  pose.gesture('reset');pose.apply(0);mesh.updateMatrixWorld(true);
  const arms=ease(t/.95)*(1-ease((t-3.35)/1.15));
  const lean=ease((t-.65)/.85)*(1-ease((t-3.05)/.85));
  // About 22 degrees across the torso, with neck/head counter-pitch to keep
  // looking at the viewer instead of bowing. Tilt follows the lean, not in unison.
  for(const [name,angle] of [['上半身',.16],['上半身1',.13],['上半身2',.09],['首',-.10],['頭',-.20]])
    get(name).quaternion.multiply(new Quaternion().setFromAxisAngle(new Vector3(1,0,0),angle*lean));
  const tilt=ease((t-1.1)/.65)*(1-ease((t-2.95)/.65));
  get('首').quaternion.multiply(new Quaternion().setFromAxisAngle(new Vector3(0,0,1),.03*tilt));
  get('頭').quaternion.multiply(new Quaternion().setFromAxisAngle(new Vector3(0,0,1),.16*tilt));
  mesh.updateMatrixWorld(true);
  const torso=get('上半身2').getWorldQuaternion(new Quaternion());
  for(const [side,sign] of [['右',-1],['左',1]]){
    const arm=get(side+'腕'),elbow=get(side+'ひじ'),hand=get(side+'手首');
    const baseArm=arm.quaternion.clone(),baseElbow=elbow.quaternion.clone();
    aim(arm,elbow,new Vector3(sign*.20,-.94,-.28).normalize().applyQuaternion(torso));
    aim(elbow,hand,new Vector3(-sign*.40,-.55,-.65).normalize().applyQuaternion(torso));
    const targetArm=arm.quaternion.clone(),targetElbow=elbow.quaternion.clone();
    arm.quaternion.copy(baseArm).slerp(targetArm,arms);
    elbow.quaternion.copy(baseElbow).slerp(targetElbow,arms);
    mesh.updateMatrixWorld(true);
    // Relax fingers downward; keep the hands apart rather than interpenetrating
    // at the centre of the back. No finger or sleeve helper bones are authored.
    const finger=byName.get(side+'中指１');
    if(finger){
      const baseHand=hand.quaternion.clone();
      aim(hand,finger,new Vector3(sign*.10,-.97,-.18).normalize().applyQuaternion(torso));
      const targetHand=hand.quaternion.clone();
      hand.quaternion.copy(baseHand).slerp(targetHand,arms);
    }
  }
  frames.push({t,rotations:Object.fromEntries(mask.map(n=>[n,get(n).quaternion.toArray().map(v=>+v.toFixed(7))]))});
}
const clip={name:'hands-behind-look',fps,duration,mask,reference:'clip-first-frame',interpolation:'authored-landmark-poses@30fps',frames,
  source:{tool:'LiveSeed offline behind-look v2 (lean + delayed head tilt)',author:'AI-authored candidate; not an original-game animation extract',authoringSha256:createHash('sha256').update(readFileSync(new URL(import.meta.url))).digest('hex')}};
writeFileSync('src/client/character/behind.generated.ts','// Generated by scripts/authoring/calibrate-behind.mjs; rotations only.\nexport const behindClips = '+JSON.stringify({'hands-behind-look':clip},null,2)+' as const;\n');
console.log('Authored behind-look: '+frames.length+' frames.');
